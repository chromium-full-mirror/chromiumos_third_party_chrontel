/* Dump out an EDID block in a simple format */
void show_edid_data(FILE* outfile, unsigned char* edid_data,
                    int items, int base)
{
  int item = 0;

  while (item < items) {
    int i;
    fprintf(outfile, " 0x%04x:  ", item + base);
    for(i=0; i < 16; i++) {
      fprintf(outfile, "%02x ", edid_data[item++]);
      if (item >= items) break;
    }
    fprintf(outfile, "\n");
  }
}


